"""Write data/halle_dacc/calcium/calcium_numbers.tex (manuscript macros, rest start).

Sources: data/halle_dacc/calcium/somatic_session.json (slow somatic pool over the
80 s theta-burst session, scripts/compute_somatic_session_calcium.py) and
data/halle_dacc/calcium/piezo_ca_canonical.json (passive Piezo1-pool readout of the
canonical S2 burst, scripts/compute_piezo_ca_readout.py).

    python scripts/render_calcium_numbers.py
"""
from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
D = REPO / "data" / "halle_dacc" / "calcium"


def f(x: float, nd: int = 2) -> str:
    return f"{x:.{nd}f}"


def main() -> None:
    s = json.loads((D / "somatic_session.json").read_text())
    p = json.loads((D / "piezo_ca_canonical.json").read_text())
    pk = p["peak_firing_uM"]
    mac = {
        # slow somatic pool, 400-burst session (uM; return time in s)
        "CaPlateauMedian": f(s["plateau_uM"]["median"]),
        "CaPlateauMin": f(s["plateau_uM"]["min"]),
        "CaPlateauMax": f(s["plateau_uM"]["max"]),
        "CaPeakMedian": f(s["peak_uM"]["median"]),
        "CaPeakMin": f(s["peak_uM"]["min"]),
        "CaPeakMax": f(s["peak_uM"]["max"]),
        "CaReturnMedian": f(s["t_return_10pct_s"]["median"], 1),
        "CaReturnMin": f(s["t_return_10pct_s"]["min"], 1),
        "CaReturnMax": f(s["t_return_10pct_s"]["max"], 1),
        "CaFocalSpikes": str(s["focal_spikes_per_burst"]),
        "CaFocalPlateau": f(s["focal_plateau_uM"]),
        "CaFocalPeak": f(s["focal_peak_uM"]),
        "CaFocalReturn": f(s["focal_t_return_s"], 1),
        "CaSomRest": f(s["model"]["Ca_rest_uM"]),
        "CaSomTau": f"{s['model']['tau_ms']:.0f}",
        "CaSomPerSpike": f(s["model"]["dCa_per_spike_uM"]),
        # passive Piezo1-pool readout, canonical 20 ms burst, firing voxels (uM)
        "CaPiezoDendMedian": f(pk["dendrite"]["median"], 1),
        "CaPiezoDendMin": f(pk["dendrite"]["min"], 1),
        "CaPiezoDendMax": f(pk["dendrite"]["max"], 1),
        "CaPiezoSomaMedian": f(pk["soma"]["median"]),
        "CaPiezoSomaMin": f(pk["soma"]["min"]),
        "CaPiezoSomaMax": f(pk["soma"]["max"]),
        "CaPiezoAISMedian": f(pk["AIS"]["median"]),
        "CaPiezoTau": f"{p['pool']['tau_decay_ms']:.0f}",
    }
    lines = ["% generated by scripts/render_calcium_numbers.py from data/halle_dacc/calcium/"
             "{somatic_session,piezo_ca_canonical}.json",
             f"% generated_at = {datetime.now().astimezone().isoformat(timespec='seconds')}",
             "% rest start (mechano_init='rest'); concentrations in uM, return times in s"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in mac.items()]
    out = D / "calcium_numbers.tex"
    out.write_text("\n".join(lines) + "\n")
    print("wrote", out)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
