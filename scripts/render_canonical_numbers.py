"""Emit LaTeX macros for the canonical halle_dacc run numbers from the validation-report
manifest, so the manuscript's Table 2, text, captions and conclusion stay consistent
with the data (JNE revision: re-cascade after the shear-solver projection fix).

Writes data/canonical_numbers.tex
Usage: python scripts/render_canonical_numbers.py [--sim halle_dacc]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
ap = argparse.ArgumentParser()
ap.add_argument("--sim", default="halle_dacc")
a = ap.parse_args()
m = json.loads((REPO / "data" / a.sim / "validation_report" / "manifest.json").read_text())
npz = np.load(REPO / "data" / a.sim / "neural_results.npz")

n = m["neural_outputs"]; e = m["elastic_outputs"]; d = m["displacement_outputs"]; ac = m["acoustic_outputs"]["transcranial"]
th = m["thermal_outputs"]; ast = m.get("astrocyte_outputs", {}); syn = m.get("synaptic_outputs", {})

def thin(x: int) -> str:            # 5468 -> 5\,468
    s = f"{x:,}"; return s.replace(",", "\\,")

fire = int(n["n_voxels_with_spike"]); spikes = int(npz["spike_count_map"].sum())
assert abs(spikes - n["spikes_per_neuron_burst_mean"] * fire) < 1.0, "manifest / npz mismatch"
T_half = 2.7
mac = {}
mac["CanFire"] = thin(fire)
mac["CanSpikes"] = thin(spikes)
mac["CanMeanSpikes"] = f"{spikes / fire:.2f}"
mac["CanPeakRate"] = f"{n['peak_rate_hz']:.0f}"
mac["CanIsoFifty"] = thin(int(round(n["iso50_volume_mm3"])))
mac["CanIsoTwentyFive"] = thin(int(round(n["iso25_volume_mm3"])))
mac["CanIsoTwentyFiveK"] = f"{n['iso25_volume_mm3'] / 1e3:.1f}"          # 10^3 mm^3, 2 s.f.
mac["CanIsoFiftyK"] = f"{n['iso50_volume_mm3'] / 1e3:.1f}"
mac["CanFiringVolK"] = f"{n['firing_volume_final_mm3'] / 1e3:.1f}"
mac["CanEligible"] = thin(int(n["n_eligible_voxels"]))
mac["CanTpeak"] = f"{e['tension']['peak_brain']:.2f}"
mac["CanTratio"] = f"{e['tension']['peak_brain'] / T_half:.2f}"
eps = e["strain"]["peak_brain"]; mant, ex = f"{eps:.2e}".split("e")
mac["CanEps"] = f"{mant}{{\\times}}10^{{{int(ex)}}}"
mac["CanUx"] = f"{d['peak_ux_um']:.2f}"
mac["CanTimeToPeak"] = f"{d['time_to_peak_ms']:.1f}"
mac["CanTau"] = f"{d['relax_tau_ms']:.1f}"
mac["CanDtShear"] = f"{d['dt_shear_us']:.1f}"
mac["CanNstepsShear"] = str(int(d["n_steps_shear"]))
mac["CanDVpassive"] = f"{e['depolarization']['delta_V_peak_brain_mV']:.0f}"
mac["CanVss"] = f"{e['depolarization']['V_rest_mV'] + e['depolarization']['delta_V_peak_brain_mV']:.0f}"
mac["CanMedianLatency"] = f"{n['median_latency_ms']:.1f}"
mac["CanVoxelVol"] = f"{n['voxel_volume_mm3']:.2f}"
mac["CanARF"] = f"{ac['arf_n_per_m3']:.0f}"
# thermal block (burst-resolved bioheat)
mac["CanDTfocus"] = f"{th['dT_focus_K']*1e3:.0f}"                       # mK, end of session
mac["CanDTskull"] = f"{th['dT_skull_peak_K']:.2f}"
mac["CanDTbrain"] = f"{th['dT_brain_peak_K']:.2f}"
mac["CanCEM"] = f"{th['cem43_peak_min']:.1e}".replace("e-0", "{\\times}10^{-").replace("e-", "{\\times}10^{-") + "}"
mac["CanDTburstBound"] = f"{th['dT_per_burst_K']*1e3:.0f}"              # conduction-free bound, mK
if th.get("burst_resolved"):
    mac["CanDTfocusEndOn"] = f"{th['dT_focus_end_of_last_on_K']*1e3:.0f}"
    mac["CanDTfocusRipple"] = f"{th['dT_focus_within_burst_ripple_K']*1e3:.1f}"
    mac["CanDTpeakRipple"] = f"{th['dT_peak_within_burst_ripple_K']*1e3:.0f}"
    mac["CanDtOn"] = f"{th['dt_on_s']*1e3:.0f}"; mac["CanDtOff"] = f"{th['dt_off_s']*1e3:.0f}"
    mac["CanNthermalSteps"] = f"{int(round(400*(0.02/th['dt_on_s'] + 0.18/th['dt_off_s']))):,}".replace(",", "\\,")
mac["CanMinusSixVol"] = f"{ac['minus_6db_vol_mm3']:.0f}"
mac["CanIsoRatio"] = f"{n['iso25_volume_mm3'] / ac['minus_6db_vol_mm3']:.0f}"
if ast:
    mac["CanAstroDrive"] = f"{ast['peak_drive']:.3f}"; mac["CanAstroDepol"] = f"{ast['focal_depolarisation_mV']:.0f}"
    mac["CanAstroRecruited"] = str(int(ast["n_recruited"]))
    an = np.load(REPO / "data" / a.sim / "astrocyte_results.npz")
    mac["CanAstroCa"] = f"{float(an['focal_Ca_uM'].max()):.2f}"; mac["CanAstroGlu"] = f"{float(an['focal_glu_uM'].max()):.1f}"
if syn:
    mac["CanSynGain"] = f"{syn['peak_combined_gain']:.1f}"; mac["CanSynRecruited"] = thin(int(syn["n_recruited"]))
    mac["CanSynFocalSpikes"] = str(int(syn["focal_n_spikes"]))

out = REPO / "data/canonical_numbers.tex"
lines = [f"% generated by scripts/render_canonical_numbers.py from data/{a.sim}/validation_report/manifest.json",
         f"% generated_at = {m.get('repro', {}).get('generated_at', '?')}"]
lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in mac.items()]
out.write_text("\n".join(lines) + "\n")
print("wrote", out); print("\n".join(lines[2:]))
