"""Render the parameter-provenance audit as LaTeX tables for the supplementary."""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parent
sys.path.insert(0, str(REPO_ROOT))

from ultraneuron import provenance_for, registered_names  # noqa: E402
from ultraneuron.provenance import ParamSource  # noqa: E402

OUT_TEX = HERE.parent / "data" / "provenance_tables.tex"


_UNICODE_REPLACE = {
    "₀": "$_0$", "₁": "$_1$", "₂": "$_2$",
    "²": "\\textsuperscript{2}", "³": "\\textsuperscript{3}",
    "⁺": "\\textsuperscript{+}", "⁻": "\\textsuperscript{$-$}",
    "α": "$\\alpha$", "β": "$\\beta$", "γ": "$\\gamma$",
    "δ": "$\\delta$", "ε": "$\\varepsilon$", "ζ": "$\\zeta$",
    "θ": "$\\theta$", "κ": "$\\kappa$", "λ": "$\\lambda$",
    "μ": "$\\mu$", "π": "$\\pi$", "ρ": "$\\rho$",
    "σ": "$\\sigma$", "τ": "$\\tau$", "φ": "$\\phi$",
    "ω": "$\\omega$", "Δ": "$\\Delta$",
    "·": "$\\cdot$", "×": "$\\times$", "∝": "$\\propto$",
    "≈": "$\\approx$", "≥": "$\\geq$", "≤": "$\\leq$",
    "→": "$\\to$", "↔": "$\\leftrightarrow$",
    "∞": "$\\infty$",
    "°": "$^\\circ$",
    "—": "---", "–": "--",
    "é": "\\'{e}", "ö": "\\\"{o}", "ü": "\\\"{u}", "ä": "\\\"{a}",
    "⟨": "$\\langle$", "⟩": "$\\rangle$",
    "‘": "`", "’": "'", "“": "``", "”": "''",
}


def _escape(s: str) -> str:
    """LaTeX-escape free-form text, then substitute unicode glyphs.

    Order matters: we escape the LaTeX-special characters first, on the
    raw input, then replace unicode characters with their (intentional)
    LaTeX-command equivalents. This way the unicode-replacement strings
    (which contain backslashes and braces) are emitted verbatim.
    """
    # Step 1: ASCII-LaTeX-escape the special characters in the raw input.
    s = (
        s.replace("\\", "\\textbackslash{}")
        .replace("&", "\\&")
        .replace("%", "\\%")
        .replace("#", "\\#")
        .replace("_", "\\_")
        .replace("^", "\\^{}")
        .replace("~", "\\textasciitilde{}")
    )
    # Step 2: substitute unicode characters with LaTeX commands.
    for u, repl in _UNICODE_REPLACE.items():
        s = s.replace(u, repl)
    return s


def render_one(name: str) -> str:
    pmap = provenance_for(name)
    title = _escape(name)
    label = name.replace("-", "_").replace(" ", "_").lower()
    lines = [
        "\\begin{table}[H]",
        f"    \\caption{{Source classification: {title}.}}",
        f"    \\label{{tab:prov_{label}}}",
        "    \\footnotesize",
        "    \\centering",
        "    \\begin{tabular}{@{}llp{6.5cm}@{}}",
        "        \\toprule",
        "        Parameter & Source & Reference / notes \\\\",
        "        \\midrule",
    ]

    by_src: dict[ParamSource, list[tuple[str, object]]] = {s: [] for s in ParamSource}
    for k, p in pmap.items():
        by_src[p.source].append((k, p))

    for src in (ParamSource.LITERATURE, ParamSource.CALIBRATED, ParamSource.ASSUMPTION, ParamSource.ESTIMATE, ParamSource.DERIVED):
        for k, prov in sorted(by_src[src]):
            cell = ""
            if prov.reference:
                cell += _escape(prov.reference)
            if prov.notes:
                if cell:
                    cell += " --- "
                cell += _escape(prov.notes)
            lines.append(
                f"        \\texttt{{{_escape(k)}}} & {src.value.title()} & {cell} \\\\",
            )
    lines += [
        "        \\bottomrule",
        "    \\end{tabular}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    blocks = [
        "% Auto-generated by scripts/render_provenance.py -- do not edit by hand.",
        "% Place \\input{data/provenance_tables} inside supplementary.tex.",
        "% (supplementary.tex preamble already loads \\usepackage{float}.)",
        "",
    ]
    # Order: channels first, then strain conversion, NICE, calcium,
    # astrocyte-relay + synaptic/voltage-gated pathway, geometry
    order = [
        "Piezo1", "TRAAK", "TREK-1", "TREK-2", "TRPV1", "TRPV4", "TRPA1",
        "strain_to_tension",
        "NICEModel",
        "SolitonModel",
        "CalciumDynamics", "SomaticCalcium", "KCaChannel",
        "AstrocyteRelay", "NMDAReceptor",
        "MechanoNav", "MechanoSynapse",
        "cortical_pyramidal_3comp",
    ]
    for name in order:
        if name not in registered_names():
            blocks.append(f"% (no provenance entry for {name})")
            continue
        blocks.append(render_one(name))
    OUT_TEX.write_text("\n".join(blocks))
    print(f"Wrote {OUT_TEX} ({len(order)} blocks).")


if __name__ == "__main__":
    main()
